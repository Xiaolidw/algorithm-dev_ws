#!/usr/bin/env python3

import argparse
import csv
import math
from collections import defaultdict
from pathlib import Path

import numpy as np


def parse_arguments():
    parser = argparse.ArgumentParser(
        description=(
            'Clean and resample dynamic-obstacle trajectory CSV data.'
        )
    )

    parser.add_argument(
        'input_csv',
        help='CSV generated by convert_rosbag.py',
    )

    parser.add_argument(
        'output_csv',
        help='Output cleaned and resampled CSV',
    )

    parser.add_argument(
        '--frequency',
        type=float,
        default=10.0,
        help='Target frequency in Hz, default: 10',
    )

    parser.add_argument(
        '--trim-start',
        type=float,
        default=1.0,
        help='Seconds removed from the beginning of each trajectory',
    )

    parser.add_argument(
        '--max-time-gap',
        type=float,
        default=0.5,
        help='Split trajectory when two samples are farther apart',
    )

    parser.add_argument(
        '--max-raw-speed',
        type=float,
        default=1.0,
        help='Split trajectory when raw displacement implies excessive speed',
    )

    parser.add_argument(
        '--minimum-segment-duration',
        type=float,
        default=5.0,
        help='Discard continuous segments shorter than this duration',
    )

    return parser.parse_args()


def load_trajectories(csv_path):
    trajectories = defaultdict(list)

    with csv_path.open(encoding='utf-8') as csv_file:
        reader = csv.DictReader(csv_file)

        required_fields = {
            'elapsed_sec',
            'obstacle_id',
            'x',
            'y',
        }

        if reader.fieldnames is None:
            raise RuntimeError('Input CSV does not contain a header.')

        missing_fields = required_fields - set(reader.fieldnames)

        if missing_fields:
            raise RuntimeError(
                f'Input CSV is missing fields: {sorted(missing_fields)}'
            )

        for line_number, row in enumerate(reader, start=2):
            try:
                timestamp = float(row['elapsed_sec'])
                x = float(row['x'])
                y = float(row['y'])
            except (TypeError, ValueError) as error:
                print(
                    f'Warning: skipped invalid row {line_number}: {error}'
                )
                continue

            if not (
                math.isfinite(timestamp)
                and math.isfinite(x)
                and math.isfinite(y)
            ):
                print(
                    f'Warning: skipped non-finite row {line_number}'
                )
                continue

            obstacle_id = row['obstacle_id'].strip()

            if not obstacle_id:
                print(
                    f'Warning: skipped row {line_number} with empty ID'
                )
                continue

            trajectories[obstacle_id].append(
                (timestamp, x, y)
            )

    for obstacle_id in trajectories:
        trajectories[obstacle_id].sort(
            key=lambda sample: sample[0]
        )

    return trajectories


def remove_startup_samples(samples, trim_start):
    if not samples:
        return []

    first_time = samples[0][0]
    minimum_time = first_time + trim_start

    return [
        sample
        for sample in samples
        if sample[0] >= minimum_time
    ]


def split_continuous_segments(
    samples,
    max_time_gap,
    max_raw_speed,
):
    if not samples:
        return []

    segments = []
    current_segment = [samples[0]]

    for current_sample in samples[1:]:
        previous_sample = current_segment[-1]

        previous_time, previous_x, previous_y = previous_sample
        current_time, current_x, current_y = current_sample

        dt = current_time - previous_time
        distance = math.hypot(
            current_x - previous_x,
            current_y - previous_y,
        )

        invalid_time = dt <= 0.0
        excessive_gap = dt > max_time_gap

        if dt > 0.0:
            raw_speed = distance / dt
        else:
            raw_speed = float('inf')

        excessive_speed = raw_speed > max_raw_speed

        if invalid_time or excessive_gap or excessive_speed:
            if current_segment:
                segments.append(current_segment)

            current_segment = [current_sample]
            continue

        current_segment.append(current_sample)

    if current_segment:
        segments.append(current_segment)

    return segments


def remove_duplicate_timestamps(samples):
    times = np.asarray(
        [sample[0] for sample in samples],
        dtype=np.float64,
    )

    xs = np.asarray(
        [sample[1] for sample in samples],
        dtype=np.float64,
    )

    ys = np.asarray(
        [sample[2] for sample in samples],
        dtype=np.float64,
    )

    unique_times, unique_indices = np.unique(
        times,
        return_index=True,
    )

    return (
        unique_times,
        xs[unique_indices],
        ys[unique_indices],
    )


def resample_segment(samples, frequency):
    times, xs, ys = remove_duplicate_timestamps(samples)

    if len(times) < 2:
        return None

    dt = 1.0 / frequency

    start_time = math.ceil(times[0] / dt) * dt
    end_time = math.floor(times[-1] / dt) * dt

    if end_time <= start_time:
        return None

    target_times = np.arange(
        start_time,
        end_time + dt * 0.5,
        dt,
        dtype=np.float64,
    )

    if len(target_times) < 2:
        return None

    target_xs = np.interp(
        target_times,
        times,
        xs,
    )

    target_ys = np.interp(
        target_times,
        times,
        ys,
    )

    velocities_x = np.gradient(
        target_xs,
        dt,
    )

    velocities_y = np.gradient(
        target_ys,
        dt,
    )

    return {
        'timestamps': target_times,
        'xs': target_xs,
        'ys': target_ys,
        'vxs': velocities_x,
        'vys': velocities_y,
    }


def calculate_segment_duration(samples):
    if len(samples) < 2:
        return 0.0

    return samples[-1][0] - samples[0][0]


def main():
    args = parse_arguments()

    if args.frequency <= 0.0:
        raise ValueError('Frequency must be greater than zero.')

    if args.trim_start < 0.0:
        raise ValueError('trim-start cannot be negative.')

    if args.max_time_gap <= 0.0:
        raise ValueError('max-time-gap must be greater than zero.')

    if args.max_raw_speed <= 0.0:
        raise ValueError('max-raw-speed must be greater than zero.')

    input_csv = Path(args.input_csv).expanduser().resolve()
    output_csv = Path(args.output_csv).expanduser().resolve()

    if not input_csv.is_file():
        raise FileNotFoundError(
            f'Input CSV does not exist: {input_csv}'
        )

    output_csv.parent.mkdir(
        parents=True,
        exist_ok=True,
    )

    trajectories = load_trajectories(input_csv)

    if not trajectories:
        raise RuntimeError(
            'No valid obstacle trajectories were found.'
        )

    output_rows = []
    global_segment_index = 0

    print(f'Input CSV: {input_csv}')
    print(f'Target frequency: {args.frequency:.3f} Hz')
    print(f'Trim start: {args.trim_start:.3f} seconds')

    for obstacle_id, raw_samples in trajectories.items():
        print()
        print(f'Processing {obstacle_id}')
        print(f'  raw samples: {len(raw_samples)}')

        trimmed_samples = remove_startup_samples(
            raw_samples,
            args.trim_start,
        )

        print(
            f'  samples after startup trim: '
            f'{len(trimmed_samples)}'
        )

        candidate_segments = split_continuous_segments(
            trimmed_samples,
            args.max_time_gap,
            args.max_raw_speed,
        )

        valid_segment_count = 0
        obstacle_output_count = 0

        for candidate_segment in candidate_segments:
            raw_duration = calculate_segment_duration(
                candidate_segment
            )

            if raw_duration < args.minimum_segment_duration:
                continue

            resampled = resample_segment(
                candidate_segment,
                args.frequency,
            )

            if resampled is None:
                continue

            global_segment_index += 1
            valid_segment_count += 1

            segment_id = (
                f'{obstacle_id}_segment_'
                f'{global_segment_index:03d}'
            )

            timestamps = resampled['timestamps']
            xs = resampled['xs']
            ys = resampled['ys']
            vxs = resampled['vxs']
            vys = resampled['vys']

            segment_start_time = timestamps[0]

            for sample_index in range(len(timestamps)):
                speed = math.hypot(
                    vxs[sample_index],
                    vys[sample_index],
                )

                output_rows.append({
                    'obstacle_id': obstacle_id,
                    'segment_id': segment_id,
                    'sample_index': sample_index,
                    'timestamp': timestamps[sample_index],
                    'segment_time': (
                        timestamps[sample_index]
                        - segment_start_time
                    ),
                    'x': xs[sample_index],
                    'y': ys[sample_index],
                    'vx': vxs[sample_index],
                    'vy': vys[sample_index],
                    'speed': speed,
                })

            obstacle_output_count += len(timestamps)

            print(
                f'  {segment_id}: '
                f'{len(timestamps)} samples, '
                f'{timestamps[-1] - timestamps[0]:.2f} seconds'
            )

        print(f'  candidate segments: {len(candidate_segments)}')
        print(f'  valid segments: {valid_segment_count}')
        print(f'  output samples: {obstacle_output_count}')

    if not output_rows:
        raise RuntimeError(
            'No valid trajectory segments remained after cleaning.'
        )

    output_rows.sort(
        key=lambda row: (
            row['obstacle_id'],
            row['segment_id'],
            row['sample_index'],
        )
    )

    with output_csv.open(
        'w',
        newline='',
        encoding='utf-8',
    ) as csv_file:
        fieldnames = [
            'obstacle_id',
            'segment_id',
            'sample_index',
            'timestamp',
            'segment_time',
            'x',
            'y',
            'vx',
            'vy',
            'speed',
        ]

        writer = csv.DictWriter(
            csv_file,
            fieldnames=fieldnames,
        )

        writer.writeheader()

        for row in output_rows:
            writer.writerow({
                'obstacle_id': row['obstacle_id'],
                'segment_id': row['segment_id'],
                'sample_index': row['sample_index'],
                'timestamp': f'{row["timestamp"]:.6f}',
                'segment_time': f'{row["segment_time"]:.6f}',
                'x': f'{row["x"]:.6f}',
                'y': f'{row["y"]:.6f}',
                'vx': f'{row["vx"]:.6f}',
                'vy': f'{row["vy"]:.6f}',
                'speed': f'{row["speed"]:.6f}',
            })

    all_speeds = np.asarray(
        [row['speed'] for row in output_rows],
        dtype=np.float64,
    )

    print()
    print('Completed')
    print(f'Output CSV: {output_csv}')
    print(f'Total output samples: {len(output_rows)}')
    print(f'Mean speed: {all_speeds.mean():.4f} m/s')
    print(f'Maximum speed: {all_speeds.max():.4f} m/s')


if __name__ == '__main__':
    main()
